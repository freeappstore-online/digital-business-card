import { createContext, useContext, useEffect, useState, type ReactNode } from 'react';

export type Locale = 'en' | 'zh' | 'ja' | 'ko' | 'es' | 'fr';

export const LOCALE_OPTIONS: { value: Locale; label: string; htmlLang: string }[] = [
  { value: 'en', label: 'English', htmlLang: 'en' },
  { value: 'zh', label: '简体中文', htmlLang: 'zh-CN' },
  { value: 'ja', label: '日本語', htmlLang: 'ja' },
  { value: 'ko', label: '한국어', htmlLang: 'ko' },
  { value: 'es', label: 'Español', htmlLang: 'es' },
  { value: 'fr', label: 'Français', htmlLang: 'fr' },
];

const VALID_LOCALES = new Set<string>(LOCALE_OPTIONS.map((o) => o.value));
const STORAGE_KEY = 'fas:digital-business-card:lang';

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && VALID_LOCALES.has(saved)) return saved as Locale;
  } catch {
    // Storage unavailable — fall back to navigator language.
  }
  const lang = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  if (lang.startsWith('zh')) return 'zh';
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  if (lang.startsWith('es')) return 'es';
  if (lang.startsWith('fr')) return 'fr';
  return 'en';
}

